const topicFallbackPairs: { pattern: RegExp; image: any }[] = [
  { pattern: /multiple sclerosis|ms|neurolog/i, image: msHeroImage },
  { pattern: /lupus|rheumatoid|arthritis|myasthenia|crohn|hashimoto|autoimmune/i, image: conditionFallbackImage },
  { pattern: /diabetes|insulin|glucose/i, image: nutritionImage },
  { pattern: /blog|article|resource|knowledge hub|guide|ebook|playbook/i, image: blogFallbackImage },
  { pattern: /story|client/i, image: storyImage },
  { pattern: /program|coaching|session/i, image: programsHeroImage },
  { pattern: /faq|question/i, image: faqImage },
];

export function getRelevantImageForTopic(topic?: string) {
  const text = (topic || '').toLowerCase();
  const match = topicFallbackPairs.find((item) => item.pattern.test(text));
  return match?.image || heroImage;
}

